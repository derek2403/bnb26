#!/usr/bin/env node
// Regenerates typed ABI modules in src/abi/** from the Foundry (contracts/) and Hardhat (openfour/startup/) builds.
//
//   npm run abi              -> core (forge inspect) + flap/launch + openfour (if their artifacts exist)
//   npm run abi -- --no-forge -> read contracts/out/*.json only (never compiles)
//
// For every target: try `forge inspect <Name> abi --json`, then contracts/out/<Name>.sol/<Name>.json, then (Hardhat)
// openfour/startup/artifacts/**/<Name>.json. When nothing is found the existing file in src/abi is left untouched,
// so the hand-written ABIs (marked "MANUAL") keep the app compiling until the real contracts exist.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const repoRoot = path.resolve(appRoot, "..");
const contractsDir = path.join(repoRoot, "contracts");
const openfourDir = path.join(repoRoot, "openfour", "startup");
const outRoot = path.join(appRoot, "src", "abi");
const noForge = process.argv.includes("--no-forge");

/** [group, contract name, export name] */
const FORGE_TARGETS = [
  ["core", "LeveragePool"],
  ["core", "PoolFactory"],
  ["core", "StabilityPool"],
  ["core", "RiskOracle"],
  ["core", "MarketCalendar"],
  ["core", "AtlasMirror"],
  ["core", "ScenarioFeed"],
  ["core", "LogAnchor"],
  ["core", "SandboxFactory"],
  ["core", "MockERC20Permit"],
  ["core", "MockRouter"],
  ["core", "SplitToken"],
  ["core", "CreatorRegistrar"],
  // Flap launch + backstop + mainnet read-only (built by other components; optional)
  ["flap", "SplitLauncher"],
  ["flap", "SplitLauncherFactory"],
  ["flap", "BackstopVault"],
  ["flap", "BackstopVaultFactory"],
  ["flap", "BackstopTreasury"],
  ["flap", "SplitStockConfig"],
  ["mainnet", "AtlasCmcAnchor"],
  ["mainnet", "NvdabLens"],
  ["core", "AtlasPullAdapter"],
];

const HARDHAT_TARGETS = [
  ["openfour", "IOpenFourCore", "OpenFourCore"],
  ["openfour", "IOpenFourTools", "OpenFourTools"],
  ["openfour", "IOpenFourVault", "OpenFourVault"],
  ["openfour", "SplitPoolMigrateModule"],
];

const PATH = `${process.env.HOME}/.foundry/bin:${process.env.PATH}`;

function forgeInspect(name) {
  if (noForge) return null;
  try {
    const raw = execFileSync("forge", ["inspect", name, "abi", "--json"], {
      cwd: contractsDir,
      env: { ...process.env, PATH },
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 300_000,
      maxBuffer: 64 * 1024 * 1024,
    }).toString();
    const start = raw.indexOf("[");
    return JSON.parse(raw.slice(start));
  } catch {
    return null;
  }
}

function forgeArtifact(name) {
  // contracts/out (default build); out-flap is a legacy fallback from the parallel build phase
  const file = ["out", "out-flap"].map((d) => path.join(contractsDir, d, `${name}.sol`, `${name}.json`)).find((f) => fs.existsSync(f));
  if (!file) return null;
  try {
    return JSON.parse(fs.readFileSync(file, "utf8")).abi ?? null;
  } catch {
    return null;
  }
}

function findFile(dir, fileName, depth = 0) {
  if (depth > 8 || !fs.existsSync(dir)) return null;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === "build-info") continue;
      const hit = findFile(full, fileName, depth + 1);
      if (hit) return hit;
    } else if (entry.name === fileName) {
      return full;
    }
  }
  return null;
}

function hardhatArtifact(name) {
  const file = findFile(path.join(openfourDir, "artifacts"), `${name}.json`);
  if (!file) return null;
  try {
    return JSON.parse(fs.readFileSync(file, "utf8")).abi ?? null;
  } catch {
    return null;
  }
}

function write(group, exportName, abi, source) {
  const dir = path.join(outRoot, group);
  fs.mkdirSync(dir, { recursive: true });
  const body =
    `// GENERATED by scripts/gen-abi.mjs from ${source}. Do not edit; run \`npm run abi\`.\n` +
    `export const ${exportName}Abi = ${JSON.stringify(abi.filter((x) => x.type !== "constructor"), null, 2)} as const;\n`;
  fs.writeFileSync(path.join(dir, `${exportName}.ts`), body);
}

const report = [];
for (const [group, name, alias] of FORGE_TARGETS) {
  let abi = forgeInspect(name);
  let src = "forge inspect";
  if (!abi) {
    abi = forgeArtifact(name);
    src = "contracts/out";
  }
  if (abi) {
    write(group, alias ?? name, abi, `${src} ${name}`);
    report.push(`ok    ${group}/${alias ?? name} (${src})`);
  } else {
    report.push(`keep  ${group}/${alias ?? name} (no artifact; existing file kept)`);
  }
}
for (const [group, name, alias] of HARDHAT_TARGETS) {
  const abi = hardhatArtifact(name);
  if (abi) {
    write(group, alias ?? name, abi, `openfour/startup/artifacts ${name}`);
    report.push(`ok    ${group}/${alias ?? name} (hardhat)`);
  } else {
    report.push(`keep  ${group}/${alias ?? name} (no hardhat artifact; existing file kept)`);
  }
}
console.log(report.join("\n"));
