#!/usr/bin/env node
// Regenerates services/src/abi/*.ts from the Foundry (contracts/) and Hardhat (openfour/startup/) builds.
//
//   npm run abi                 # all targets; missing artifacts keep the existing (hand-written) file
//   npm run abi -- --only core  # only the core contracts
//
// Core contracts: `forge inspect <Contract> abi --json` (falls back to contracts/out/<C>.sol/<C>.json).
// Flap / backstop / OpenFour contracts are written concurrently by other components, so their files in
// src/abi/ start as hand-written human-readable ABIs. Once the artifacts exist this script overwrites
// them with the compiled ABI (the exported const name stays the same, so no import changes).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const servicesDir = resolve(here, "..");
const repo = resolve(servicesDir, "..");
const contractsDir = join(repo, "contracts");
const openfourDir = join(repo, "openfour", "startup");
const abiDir = join(servicesDir, "src", "abi");

/** [exportName, fileName, candidate contract names, source] */
const CORE = [
  ["leveragePoolAbi", "LeveragePool", ["LeveragePool"]],
  ["poolFactoryAbi", "PoolFactory", ["PoolFactory"]],
  ["stabilityPoolAbi", "StabilityPool", ["StabilityPool"]],
  ["riskOracleAbi", "RiskOracle", ["RiskOracle"]],
  ["marketCalendarAbi", "MarketCalendar", ["MarketCalendar"]],
  ["atlasMirrorAbi", "AtlasMirror", ["AtlasMirror"]],
  ["scenarioFeedAbi", "ScenarioFeed", ["ScenarioFeed"]],
  ["logAnchorAbi", "LogAnchor", ["LogAnchor"]],
  ["sandboxFactoryAbi", "SandboxFactory", ["SandboxFactory"]],
  ["splitTokenAbi", "SplitToken", ["SplitToken"]],
  ["mockErc20Abi", "MockERC20Permit", ["MockERC20Permit"]],
  ["mockRouterAbi", "MockRouter", ["MockRouter"]],
  ["mockAggregatorAbi", "MockAggregator", ["MockAggregator"]],
  ["uniswapV2RouterAbi", "IUniswapV2Router02", ["IUniswapV2Router02"]],
  ["creatorRegistrarAbi", "CreatorRegistrar", ["CreatorRegistrar"]],
];

/** Written concurrently by the Flap / backstop / mainnet components (Foundry). */
const FOUNDRY_LATER = [
  ["backstopVaultAbi", "BackstopVault", ["BackstopVault"]],
  ["backstopTreasuryAbi", "BackstopTreasury", ["BackstopTreasury"]],
  ["splitLauncherAbi", "SplitLauncher", ["SplitLauncher"]],
  ["splitLauncherFactoryAbi", "SplitLauncherFactory", ["SplitLauncherFactory"]],
  ["atlasCmcAnchorAbi", "AtlasCmcAnchor", ["AtlasCmcAnchor"]],
];

/** OpenFour (Hardhat artifacts under openfour/startup/artifacts). */
const OPENFOUR = [
  ["splitPoolMigrateModuleAbi", "SplitPoolMigrateModule", ["SplitPoolMigrateModule", "SplitFloorMigrateModule"]],
];

const only = process.argv.includes("--only") ? process.argv[process.argv.indexOf("--only") + 1] : null;

function forgeInspect(name) {
  const forge = process.env.FORGE_BIN || join(process.env.HOME || "", ".foundry", "bin", "forge");
  const bin = existsSync(forge) ? forge : "forge";
  try {
    const out = execFileSync(bin, ["inspect", name, "abi", "--json"], {
      cwd: contractsDir,
      stdio: ["ignore", "pipe", "pipe"],
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    });
    return JSON.parse(out);
  } catch {
    return null;
  }
}

function foundryOut(name) {
  // default build dir (contracts/out); out-flap / out-scripts are legacy fallbacks from the parallel build phase
  for (const dir of ["out", "out-flap", "out-scripts"]) {
    const p = join(contractsDir, dir, `${name}.sol`, `${name}.json`);
    if (!existsSync(p)) continue;
    try {
      const abi = JSON.parse(readFileSync(p, "utf8")).abi;
      if (Array.isArray(abi)) return abi;
    } catch {
      /* try the next dir */
    }
  }
  return null;
}

function findHardhatArtifact(dir, name) {
  if (!existsSync(dir)) return null;
  const stack = [dir];
  while (stack.length) {
    const d = stack.pop();
    for (const entry of readdirSync(d)) {
      const p = join(d, entry);
      const st = statSync(p);
      if (st.isDirectory()) {
        if (entry === "build-info") continue;
        stack.push(p);
      } else if (entry === `${name}.json`) {
        try {
          const j = JSON.parse(readFileSync(p, "utf8"));
          if (Array.isArray(j.abi)) return j.abi;
        } catch {
          /* ignore */
        }
      }
    }
  }
  return null;
}

function write(exportName, fileName, abi, source) {
  const body =
    `// AUTO-GENERATED by scripts/gen-abi.mjs from ${source}. Do not edit by hand; run \`npm run abi\`.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(abiDir, `${fileName}.ts`), body);
  console.log(`  wrote src/abi/${fileName}.ts (${abi.length} items, ${source})`);
}

let missing = 0;
function run(list, resolver, label) {
  console.log(`[abi] ${label}`);
  for (const [exportName, fileName, names] of list) {
    let abi = null;
    let src = "";
    for (const n of names) {
      const r = resolver(n);
      if (r) {
        abi = r.abi;
        src = r.src;
        break;
      }
    }
    if (abi) write(exportName, fileName, abi, src);
    else {
      missing++;
      console.log(`  skip ${fileName}: no artifact yet (keeping existing src/abi/${fileName}.ts)`);
    }
  }
}

if (!only || only === "core") {
  run(
    CORE,
    (n) => {
      const a = forgeInspect(n) ?? foundryOut(n);
      return a ? { abi: a, src: `contracts (${n})` } : null;
    },
    "core (forge inspect)",
  );
}
if (!only || only === "flap") {
  run(
    FOUNDRY_LATER,
    (n) => {
      const a = foundryOut(n) ?? forgeInspect(n);
      return a ? { abi: a, src: `contracts (${n})` } : null;
    },
    "flap / backstop / mainnet (contracts/out)",
  );
}
if (!only || only === "openfour") {
  run(
    OPENFOUR,
    (n) => {
      const a = findHardhatArtifact(join(openfourDir, "artifacts"), n);
      return a ? { abi: a, src: `openfour/startup artifacts (${n})` } : null;
    },
    "openfour (hardhat artifacts)",
  );
}
console.log(`[abi] done${missing ? `, ${missing} kept as hand-written` : ""}`);
